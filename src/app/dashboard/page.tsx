function normalizeUrl(value: string) {
  const trimmed = value.trim();
  if (!trimmed) return "";
  return /^https?:\/\//i.test(trimmed) ? trimmed : `https://${trimmed}`;
}

const DANGEROUS_PROTOCOLS = /^(javascript|vbscript|data|file):/i;
const DANGEROUS_KEYWORDS = [/\bj\s*a\s*v\s*a\s*s\s*c\s*r\s*i\s*p\s*t\s*:/i, /\bd\s*a\s*t\s*a\s*:/i, /\bv\s*b\s*s\s*c\s*r\s*i\s*p\s*t\s*:/i, /\bf\s*i\s*l\s*e\s*:/i];

function isDangerousUrl(value: string): boolean {
  const lower = value.toLowerCase();
  if (DANGEROUS_PROTOCOLS.test(lower)) return true;
  for (const kw of DANGEROUS_KEYWORDS) {
    if (kw.test(lower)) return true;
  }
  return false;
}

